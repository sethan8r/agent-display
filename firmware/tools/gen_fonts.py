"""Download the fonts the firmware embeds; LVGL's TinyTTF renders them on the board.

- Inter (regular + semibold) for text
- Lucide icon font for icons (same icon set as design/index.html)

Usage: py -3 firmware/tools/gen_fonts.py
Output: firmware/fonts/*.ttf + licenses (embedded via board_build.embed_files), firmware/src/app/icons.h
"""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fonts"
WEIGHTS = (400, 600)
OFL = "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/OFL.txt"
LUCIDE = "https://unpkg.com/lucide-static@0.469.0"
# name in the firmware: Lucide names to try (they get renamed between versions)
ICONS = {
    "edit": ["pencil"], "run": ["terminal"], "read": ["file-text"], "find": ["search"], "web": ["globe"],
    "agent": ["users"], "warn": ["triangle-alert", "alert-triangle"], "question": ["circle-help", "help-circle"],
    "plan": ["clipboard-list"], "check": ["check"], "error": ["circle-x", "x-circle"], "dot": ["dot"],
    "other": ["ellipsis"], "gear": ["settings"], "up": ["chevron-up"], "down": ["chevron-down"],
    "back": ["chevron-left"], "plug": ["unplug"], "folder": ["folder"], "cpu": ["cpu"], "clock": ["clock"],
    "coffee": ["coffee"], "refresh": ["refresh-cw"], "download": ["download"], "sun": ["sun"], "moon": ["moon"],
    "target": ["crosshair"],
}


def fetch(url, headers=None):
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers or {}), timeout=60).read()


def inter(weight):
    # an old User-Agent makes Google Fonts serve one plain TTF instead of woff2 subsets
    css = fetch(f"https://fonts.googleapis.com/css2?family=Inter:wght@{weight}", {"User-Agent": "Mozilla/4.0"}).decode()
    urls = re.findall(r"url\((https://[^)]+)\)", css)
    assert len(urls) == 1, f"expected one TTF for weight {weight}, got {urls}"
    return fetch(urls[0])


def is_ttf(data):
    return data[:4] in (b"\x00\x01\x00\x00", b"true")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for w in WEIGHTS:
        data = inter(w)
        assert is_ttf(data), "Inter is not a TrueType file"
        (OUT / f"Inter-{w}.ttf").write_bytes(data)
    (OUT / "OFL-Inter.txt").write_bytes(fetch(OFL))

    ttf = fetch(f"{LUCIDE}/font/lucide.ttf")
    assert is_ttf(ttf), "Lucide is not a TrueType file"
    (OUT / "lucide.ttf").write_bytes(ttf)
    (OUT / "LICENSE-Lucide.txt").write_bytes(fetch(f"{LUCIDE}/LICENSE"))

    css = fetch(f"{LUCIDE}/font/lucide.css").decode()
    codes = dict(re.findall(r'\.icon-([a-z0-9-]+):+before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
    lines = ["#pragma once", "// Lucide icon glyphs as UTF-8 strings. Generated by tools/gen_fonts.py — do not edit.", "namespace icon {"]
    for name, candidates in ICONS.items():
        code = next((codes[c] for c in candidates if c in codes), None)
        assert code, f"no Lucide icon for {name}: {candidates}"
        utf8 = "".join(f"\\x{b:02X}" for b in chr(int(code, 16)).encode("utf-8"))
        lines.append(f'inline constexpr const char* {name} = "{utf8}";  // {candidates[0]} U+{code.upper()}')
    lines.append("}  // namespace icon\n")
    (ROOT / "src" / "app").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "app" / "icons.h").write_text("\n".join(lines), encoding="utf-8")
    print("fonts and", len(ICONS), "icons written")


if __name__ == "__main__":
    main()
