"""Fonts for the firmware: download the TTFs, then pre-render them into LVGL bitmap fonts.

- Inter (regular + semibold) for text, 10..16 px, and semibold 24 px for the empty screen phrase
- Font Awesome Free Solid for icons (same icons as design/index.html), 12 / 16 / 30 / 56 px

Pre-rendered fonts live in flash and need no RAM at all; rendering TTFs on the board (TinyTTF) ran the heap out.

Usage: py -3 firmware/tools/gen_fonts.py   (needs Pillow)
Output: firmware/fonts/*.ttf + licenses (sources), firmware/src/app/fonts/*.c + fonts.h, firmware/src/app/icons.h
"""
import re
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fonts"
WEIGHTS = (400, 600)
OFL = "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/OFL.txt"
FA = "https://unpkg.com/@fortawesome/fontawesome-free@6.5.2"
# name in the firmware: Font Awesome name (keep in sync with FA_ICONS in design/index.html)
ICONS = {
    "edit": "pen", "run": "terminal", "read": "file-lines", "find": "magnifying-glass", "web": "globe",
    "agent": "users", "warn": "triangle-exclamation", "question": "circle-question", "plan": "clipboard-list",
    "check": "check", "error": "circle-xmark", "dot": "circle", "other": "ellipsis", "gear": "gear",
    "up": "chevron-up", "down": "chevron-down", "back": "chevron-left", "plug": "plug-circle-xmark",
    "folder": "folder", "cpu": "microchip", "clock": "clock", "coffee": "mug-hot", "refresh": "rotate-right",
    "download": "download", "sun": "sun", "moon": "moon", "target": "crosshairs",
}


TEXT_PX = range(10, 17)
TITLE_PX = 24  # semibold only: the empty screen phrase
ICON_PX = (12, 16, 30, 56)
# Latin + Latin-1, Cyrillic (Russian with Ё, Ukrainian), and the typography the UI prints: – — … № ← ↑ → ↓
TEXT_CODES = [*range(0x20, 0x7F), *range(0xA0, 0x100), 0x401, 0x404, 0x406, 0x407, *range(0x410, 0x450), 0x451, 0x454,
              0x456, 0x457, 0x490, 0x491, 0x2013, 0x2014, 0x2026, 0x2116, *range(0x2190, 0x2194)]


def fetch(url, headers=None):
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers or {}), timeout=60).read()


def is_ttf(data):
    return data[:4] in (b"\x00\x01\x00\x00", b"true")


def inter(weight):
    # an old User-Agent makes Google Fonts serve one plain TTF instead of woff2 subsets
    css = fetch(f"https://fonts.googleapis.com/css2?family=Inter:wght@{weight}", {"User-Agent": "Mozilla/4.0"}).decode()
    urls = re.findall(r"url\((https://[^)]+)\)", css)
    assert len(urls) == 1, f"expected one TTF for weight {weight}, got {urls}"
    return fetch(urls[0])


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for w in WEIGHTS:
        data = inter(w)
        assert is_ttf(data), "Inter is not a TrueType file"
        (OUT / f"Inter-{w}.ttf").write_bytes(data)
    (OUT / "OFL-Inter.txt").write_bytes(fetch(OFL))

    ttf = fetch(f"{FA}/webfonts/fa-solid-900.ttf")
    assert is_ttf(ttf), "Font Awesome is not a TrueType file"
    (OUT / "fa-solid.ttf").write_bytes(ttf)
    (OUT / "LICENSE-FontAwesome.txt").write_bytes(fetch(f"{FA}/LICENSE.txt"))

    css = fetch(f"{FA}/css/all.css").decode()
    codes = dict(re.findall(r'\.fa-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
    lines = ["#pragma once", "// Font Awesome Solid glyphs as UTF-8 strings. Generated by tools/gen_fonts.py — do not edit.",
             "namespace icon {"]
    for name, fa in ICONS.items():
        code = codes[fa]
        utf8 = "".join(f"\\x{b:02X}" for b in chr(int(code, 16)).encode("utf-8"))
        lines.append(f'inline constexpr const char* {name} = "{utf8}";  // {fa} U+{code.upper()}')
    lines.append("}  // namespace icon\n")
    (ROOT / "src" / "app" / "icons.h").write_text("\n".join(lines), encoding="utf-8")

    out = ROOT / "src" / "app" / "fonts"
    out.mkdir(parents=True, exist_ok=True)
    names = []
    for w in WEIGHTS:
        for px in TEXT_PX:
            names.append(bitmap_font(OUT / f"Inter-{w}.ttf", px, TEXT_CODES, f"inter_{w}_{px}", out))
    names.append(bitmap_font(OUT / "Inter-600.ttf", TITLE_PX, TEXT_CODES, f"inter_600_{TITLE_PX}", out))
    icon_codes = sorted(int(codes[fa], 16) for fa in ICONS.values())
    for px in ICON_PX:
        names.append(bitmap_font(OUT / "fa-solid.ttf", px, icon_codes, f"fa_solid_{px}", out))
    header = ["#pragma once", "// Pre-rendered LVGL fonts. Generated by tools/gen_fonts.py — do not edit.", "#include <lvgl.h>", "",
              '#ifdef __cplusplus\nextern "C" {\n#endif', *(f"extern const lv_font_t {n};" for n in names),
              "#ifdef __cplusplus\n}\n#endif", "",
              f"constexpr int TEXT_PX_MIN = {TEXT_PX[0]}, TEXT_PX_MAX = {TEXT_PX[-1]};",
              "inline const lv_font_t* const TEXT_FONTS[2][TEXT_PX_MAX - TEXT_PX_MIN + 1] = {",
              *("  {" + ", ".join(f"&inter_{w}_{px}" for px in TEXT_PX) + "}," for w in WEIGHTS), "};",
              f"constexpr int TITLE_PX = {TITLE_PX};", f"inline const lv_font_t* const TITLE_FONT = &inter_600_{TITLE_PX};",
              "inline const lv_font_t* icon_font(int px) { return " +
              " : ".join(f"px <= {p} ? &fa_solid_{p}" for p in ICON_PX[:-1]) + f" : &fa_solid_{ICON_PX[-1]}; }}", ""]
    (out / "fonts.h").write_text("\n".join(header), encoding="utf-8")
    print(len(names), "bitmap fonts and", len(ICONS), "icons written")


def bitmap_font(ttf, px, codes, name, out):
    """Render one font size into an LVGL fmt_txt font: 4 bpp, glyph bitmaps packed continuously (like lv_font_conv)."""
    f = ImageFont.truetype(str(ttf), px)
    ascent, descent = f.getmetrics()
    bitmap, dsc = bytearray(), []
    for cp in codes:
        ch = chr(cp)
        adv = round(f.getlength(ch) * 16)
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")  # relative to the baseline origin, y grows down
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            dsc.append((len(bitmap), adv, 0, 0, 0, 0))
            continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
        px4 = [(v * 15 + 127) // 255 for v in im.tobytes()]
        if len(px4) % 2:
            px4.append(0)
        start = len(bitmap)
        bitmap += bytes(px4[i] << 4 | px4[i + 1] for i in range(0, len(px4), 2))
        dsc.append((start, adv, w, h, x0, -y1))  # ofs_y: bottom of the box above the baseline
    cap_h = -f.getbbox("H", anchor="ls")[1] if 0x48 in codes else ascent
    x_h = -f.getbbox("x", anchor="ls")[1] if 0x78 in codes else ascent

    runs, glyph_id = [], 1  # cmaps: runs of consecutive code points (glyph id 0 is reserved)
    for cp in codes:
        if runs and cp == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([cp, 1, glyph_id])
        glyph_id += 1

    hexes = ", ".join(f"0x{b:02x}" for b in bitmap)
    c = [f"// {ttf.name} {px} px, 4 bpp. Generated by tools/gen_fonts.py — do not edit.", "#include <lvgl.h>", "",
         "static const uint8_t glyph_bitmap[] = {", "\n".join("    " + hexes[i:i + 96].strip() for i in range(0, len(hexes), 96)),
         "};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
         "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
    c += [f"    {{.bitmap_index = {d[0]}, .adv_w = {d[1]}, .box_w = {d[2]}, .box_h = {d[3]}, .ofs_x = {d[4]}, .ofs_y = {d[5]}}},"
          for d in dsc]
    c += ["};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {"]
    c += [f"    {{.range_start = {r[0]}, .range_length = {r[1]}, .glyph_id_start = {r[2]}, .unicode_list = NULL, "
          f".glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}," for r in runs]
    c += ["};", "", "static const lv_font_fmt_txt_dsc_t font_dsc = {",
          "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,",
          f"    .cmap_num = {len(runs)}, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,", "};", "",
          f"const lv_font_t {name} = {{",
          "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
          "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
          f"    .line_height = {ascent + descent}, .base_line = {descent}, .cap_height = {cap_h}, .x_height = {x_h},",
          "    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -1, .underline_thickness = 1, .static_bitmap = 1,",
          "    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL,", "};", ""]
    (out / f"{name}.c").write_text("\n".join(c), encoding="utf-8")
    assert len(bitmap) < 1 << 20 and all(d[1] < 4096 and d[2] < 256 and d[3] < 256 for d in dsc), name
    return name


if __name__ == "__main__":
    main()
