"""Download the fonts the firmware embeds; LVGL's TinyTTF renders them on the board.

- Inter (regular + semibold) for text
- Font Awesome Free Solid for icons (same icons as design/index.html)

Usage: py -3 firmware/tools/gen_fonts.py
Output: firmware/fonts/*.ttf + licenses (embedded via board_build.embed_files), firmware/src/app/icons.h
"""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fonts"
WEIGHTS = (400, 600)
OFL = "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/OFL.txt"
FA = "https://unpkg.com/@fortawesome/fontawesome-free@6.5.2"
# name in the firmware: Font Awesome name (keep in sync with FA_ICONS in design/index.html)
ICONS = {
    "edit": "pen", "run": "terminal", "read": "file-lines", "find": "magnifying-glass", "web": "globe",
    "agent": "users", "warn": "triangle-exclamation", "question": "circle-question", "plan": "clipboard-list",
    "check": "check", "error": "circle-xmark", "dot": "circle", "other": "ellipsis", "gear": "gear",
    "up": "chevron-up", "down": "chevron-down", "back": "chevron-left", "plug": "plug-circle-xmark",
    "folder": "folder", "cpu": "microchip", "clock": "clock", "coffee": "mug-hot", "refresh": "rotate-right",
    "download": "download", "sun": "sun", "moon": "moon", "target": "crosshairs",
}


def fetch(url, headers=None):
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers or {}), timeout=60).read()


def is_ttf(data):
    return data[:4] in (b"\x00\x01\x00\x00", b"true")


def inter(weight):
    # an old User-Agent makes Google Fonts serve one plain TTF instead of woff2 subsets
    css = fetch(f"https://fonts.googleapis.com/css2?family=Inter:wght@{weight}", {"User-Agent": "Mozilla/4.0"}).decode()
    urls = re.findall(r"url\((https://[^)]+)\)", css)
    assert len(urls) == 1, f"expected one TTF for weight {weight}, got {urls}"
    return fetch(urls[0])


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for w in WEIGHTS:
        data = inter(w)
        assert is_ttf(data), "Inter is not a TrueType file"
        (OUT / f"Inter-{w}.ttf").write_bytes(data)
    (OUT / "OFL-Inter.txt").write_bytes(fetch(OFL))

    ttf = fetch(f"{FA}/webfonts/fa-solid-900.ttf")
    assert is_ttf(ttf), "Font Awesome is not a TrueType file"
    (OUT / "fa-solid.ttf").write_bytes(ttf)
    (OUT / "LICENSE-FontAwesome.txt").write_bytes(fetch(f"{FA}/LICENSE.txt"))

    css = fetch(f"{FA}/css/all.css").decode()
    codes = dict(re.findall(r'\.fa-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
    lines = ["#pragma once", "// Font Awesome Solid glyphs as UTF-8 strings. Generated by tools/gen_fonts.py — do not edit.",
             "namespace icon {"]
    for name, fa in ICONS.items():
        code = codes[fa]
        utf8 = "".join(f"\\x{b:02X}" for b in chr(int(code, 16)).encode("utf-8"))
        lines.append(f'inline constexpr const char* {name} = "{utf8}";  // {fa} U+{code.upper()}')
    lines.append("}  // namespace icon\n")
    (ROOT / "src" / "app" / "icons.h").write_text("\n".join(lines), encoding="utf-8")
    print("fonts and", len(ICONS), "icons written")


if __name__ == "__main__":
    main()
