"""Icon set comparison for the "icons" test firmware: Lucide, Phosphor Bold, Phosphor Fill, Font Awesome Solid.

Usage: py -3 firmware/tools/gen_icon_sets.py   (after gen_fonts.py, which provides Lucide)
Output: firmware/fonts/test/*.ttf (git-ignored), firmware/src/icontest/icon_sets.h
"""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fonts" / "test"
NAMES = ["edit", "run", "read", "find", "web", "agent", "warn", "question", "plan", "check", "error", "dot", "other",
         "gear", "up", "down", "back", "plug", "folder", "cpu", "clock", "coffee", "refresh", "download", "sun", "moon",
         "target"]
PH = "https://unpkg.com/@phosphor-icons/web@2.1.1"
FA = "https://unpkg.com/@fortawesome/fontawesome-free@6.5.2"
LUCIDE = "https://unpkg.com/lucide-static@0.469.0"
SETS = [  # title, font file, css url, selector regex with {n}, names in the same order as NAMES
    ("Lucide", None, f"{LUCIDE}/font/lucide.css", r"\.icon-{n}:+before",
     "pencil terminal file-text search globe users triangle-alert circle-help clipboard-list check circle-x dot ellipsis "
     "settings chevron-up chevron-down chevron-left unplug folder cpu clock coffee refresh-cw download sun moon crosshair"),
    ("Phosphor Bold", (f"{PH}/src/bold/Phosphor-Bold.ttf", "ph-bold.ttf"), f"{PH}/src/bold/style.css", r"\.ph-bold\.ph-{n}:before",
     "pencil-simple terminal-window file-text magnifying-glass globe users warning question clipboard-text check x-circle "
     "dot-outline dots-three gear caret-up caret-down caret-left plugs folder cpu clock coffee arrows-clockwise "
     "download-simple sun moon crosshair"),
    ("Phosphor Fill", (f"{PH}/src/fill/Phosphor-Fill.ttf", "ph-fill.ttf"), f"{PH}/src/fill/style.css", r"\.ph-fill\.ph-{n}:before",
     "pencil-simple terminal-window file-text magnifying-glass globe users warning question clipboard-text check-circle "
     "x-circle dot-outline dots-three-circle gear caret-up caret-down caret-left plugs folder cpu clock coffee "
     "arrows-clockwise download-simple sun moon crosshair"),
    ("Font Awesome", (f"{FA}/webfonts/fa-solid-900.ttf", "fa-solid.ttf"), f"{FA}/css/all.css", r"\.fa-{n}::before",
     "pen terminal file-lines magnifying-glass globe users triangle-exclamation circle-question clipboard-list check "
     "circle-xmark circle ellipsis gear chevron-up chevron-down chevron-left plug-circle-xmark folder microchip clock "
     "mug-hot rotate-right download sun moon crosshairs"),
]


def fetch(url):
    return urllib.request.urlopen(url, timeout=60).read()


def utf8(code):
    return "".join(f"\\x{b:02X}" for b in chr(int(code, 16)).encode("utf-8"))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "LICENSE-Phosphor.txt").write_bytes(fetch(f"{PH}/LICENSE"))
    (OUT / "LICENSE-FontAwesome.txt").write_bytes(fetch(f"{FA}/LICENSE.txt"))
    rows = []
    for title, font, css_url, selector, names in SETS:
        if font:
            (OUT / font[1]).write_bytes(fetch(font[0]))
        css = fetch(css_url).decode()
        glyphs = []
        for n in names.split():
            m = re.search(selector.format(n=re.escape(n)) + r'\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)
            assert m, f"{title}: no icon {n}"
            glyphs.append(f'"{utf8(m.group(1))}"')
        assert len(glyphs) == len(NAMES), title
        rows.append(f'  {{"{title}", {{{", ".join(glyphs)}}}}},')
    header = ["#pragma once", "// Generated by tools/gen_icon_sets.py — do not edit.",
              f"static constexpr int ICON_COUNT = {len(NAMES)};",
              "static const char* const ICON_NAMES[ICON_COUNT] = {" + ", ".join(f'"{n}"' for n in NAMES) + "};",
              "struct IconSet { const char* title; const char* glyph[ICON_COUNT]; };",
              "static const IconSet ICON_SETS[] = {", *rows, "};", ""]
    (ROOT / "src" / "icontest").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "icontest" / "icon_sets.h").write_text("\n".join(header), encoding="utf-8")
    print("ok:", ", ".join(s[0] for s in SETS))


if __name__ == "__main__":
    main()
